create or replace function public.current_property_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select property_id
  from public.property_users
  where user_id = auth.uid()
  limit 1;
$$;

grant execute on function public.current_property_id() to authenticated;

alter table public.properties enable row level security;

drop policy if exists "property users read own property" on public.properties;
create policy "property users read own property"
  on public.properties for select
  using (id = public.current_property_id());

drop policy if exists "property users update own property" on public.properties;
create policy "property users update own property"
  on public.properties for update
  using (id = public.current_property_id())
  with check (id = public.current_property_id());

